const workHours = (job) => {
  const d = job.daysPerWeek || 3;
  if (job.weekend) return `每週 ${d} 天（含週末），依排班，每天約 8 小時`;
  return d >= 5 ? '週一至週五 09:30–18:30' : `週一至週五擇 ${d} 天，09:30–18:30（可與主管討論）`;
};

// 把詳細資料加到示範職缺上
export function withDetails(job) {
  const d = DETAILS[job.title];
  const group = GROUP[job.category] || 'office';
  if (!d) return job;
  const [address, companyIntro, responsibilities, headcount] = d;
  return {
    ...job,
    location: address,
    companyIntro,
    responsibilities,
    headcount,
    workHours: workHours(job),
    startDate: '錄取後兩週內到職，可配合學期時間調整',
    interviewStages: STAGES[group],
    applyMaterials: MATERIALS[group],
  };
}
